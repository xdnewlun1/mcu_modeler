#!/bin/sh
# Build the STM32F2 samples (STM32F205/F207/F215/F217: Cortex-M3, no FPU, 120 MHz) into build/<name>.elf and .bin
# (clang --target=thumbv7m-none-eabi -mcpu=cortex-m3 -mfloat-abi=soft + ld.lld).
# * startup.c: the 81-entry vector table of RM0033 Table 20 (no FPU vector, no CPACR write).
# * The linker script is ../samples_stm32/link.ld (1 MB flash at 0x08000000, 128 KB SRAM at 0x20000000: the F405
#   samples never used the CCM RAM, so the F2 memory map is the same) and the register header ../samples_stm32/stm32f405.h
#   (same register layout for every block the samples touch).
# * SHARED: STM32F405 samples that run on the F2 unchanged (reset clock HSI 16 MHz; only blocks the F2 has).
# * GEN: STM32F405 samples that program the 168 MHz HAL clock tree, rebuilt from the same source with the F2 tree
#   (RM0033: PLL M=8 N=240 P=2 Q=5 -> 120 MHz SYSCLK and 48 MHz PLL48CLK, APB1 /4 = 30 MHz, APB2 /2 = 60 MHz, 3 flash
#   wait states, Ethernet MDC range CR=001 for 100-120 MHz) by the sed substitutions below; each substitution must
#   match, so a change of the F405 source stops the build instead of producing a wrong F2 image.
# * Local: clock120_uart.c (120 MHz + USART1 + TIM2 1 ms IRQ), cryp_hash.c (STM32F215/F217 CRYP + HASH).
set -eu
cd "$(dirname "$0")"
CC=${CC:-clang}
PY=${PY:-"$(cd ../.. && pwd)/.venv/bin/python"}
F4=../samples_stm32
CFLAGS="--target=thumbv7m-none-eabi -mcpu=cortex-m3 -mfloat-abi=soft -mthumb -O1 -g \
 -ffreestanding -nostdlib -fno-builtin -Wall -Wextra -I$F4"
LDFLAGS="-T $F4/link.ld -fuse-ld=lld -Wl,--image-base=0x08000000 -Wl,-e,Reset_Handler -Wl,--gc-sections"
SHARED="blinky button_mirror uart_echo uart_link_echo exti_irq tim_pwm tim_capture adc_tim_trigger uart_dma spi_master
 spi_slave spi_flash i2c_eeprom i2c_slave can_echo rtc_alarm sdio_card fsmc_sram dcmi_capture"
GEN="tim_irq stop_rtc_wakeup eth_ping usb_cdc"
mkdir -p build build/gen

bin() {
    if command -v llvm-objcopy >/dev/null 2>&1; then
        llvm-objcopy -O binary "build/$1.elf" "build/$1.bin"
    else
        "$PY" ../samples/elf2bin.py "build/$1.elf" "build/$1.bin"
    fi
}

cc() {   # cc <name> <source>
    echo "CC  $1"
    $CC $CFLAGS -ffunction-sections -fdata-sections $LDFLAGS -o "build/$1.elf" startup.c "$2" -Wl,-Map,"build/$1.map"
    bin "$1"
}

subst() {   # subst <file> <sed expression> : apply, and fail when it changed nothing
    before=$(cksum < "$1")
    sed -i -e "$2" "$1"
    if [ "$(cksum < "$1")" = "$before" ]; then
        echo "build.sh: '$2' does not match $1 (the STM32F405 source changed?)" >&2
        exit 1
    fi
}

for name in $SHARED; do
    cc "$name" "$F4/$name.c"
done

for name in $GEN; do
    g="build/gen/$name.c"
    { echo "/* GENERATED by firmware/samples_stm32f2/build.sh from ../samples_stm32/$name.c: STM32F2 120 MHz clock tree */"
      echo "#line 1 \"$name.c\""
      cat "$F4/$name.c"; } > "$g"
    subst "$g" 's/(336u << 6)/(240u << 6)/'                       # PLLN 336 -> 240 (VCO 240 MHz)
    subst "$g" 's/(7u << 24)/(5u << 24)/'                         # PLLQ 7 -> 5 (PLL48CLK 48 MHz)
    subst "$g" 's/FLASH_ACR_LATENCY_5WS/3u/'                      # 3 wait states (RM0033 Table 3)
    case "$name" in
        tim_irq)         subst "$g" 's/TIM2->PSC = 84u - 1u;/TIM2->PSC = 60u - 1u;/' ;;   # APB1 timer clock 60 MHz
        stop_rtc_wakeup) subst "$g" 's/USART_BRR(84000000u,/USART_BRR(60000000u,/' ;;
        eth_ping)        subst "$g" 's/USART_BRR(84000000u,/USART_BRR(60000000u,/'
                         subst "$g" 's/(4u << 2) | 1u;/(1u << 2) | 1u;/' ;;                  # MDC CR=001: HCLK/62
        usb_cdc)         subst "$g" 's/delay_cycles(168000u \* 30u/delay_cycles(120000u * 30u/' ;;
    esac
    cc "$name" "$g"
done

for src in *.c; do
    name=${src%.c}
    [ "$name" = startup ] && continue
    cc "$name" "$src"
done
echo "ok: $(ls build/*.elf | wc -l) samples built"
