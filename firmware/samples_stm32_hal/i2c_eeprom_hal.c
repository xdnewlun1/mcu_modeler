/* i2c_eeprom_hal: ST's STM32CubeF4 HAL I2C driver against a 24C02 EEPROM (board part i2c_eeprom at 0x50) on an
 * STM32F405ZG.
 *
 * Clock:  HSE 8 MHz -> PLL -> 168 MHz, APB1 = 42 MHz (I2C1 kernel clock), APB2 = 84 MHz (USART1).
 * I2C:    I2C1 on PB6 (SCL) / PB7 (SDA), AF4 open-drain with pull-ups, 100 kHz standard mode (HAL_I2C_Init:
 *         FREQ = 42, CCR = 210, TRISE = 43).
 * UART:   USART1 115200 8N1 on PA9 (TX), polled HAL_UART_Transmit.
 * Program: HAL_I2C_IsDeviceReady(0x50); HAL_I2C_Mem_Write "HAL I2C!" at 0x20 (one 8-byte page); poll the write
 *         cycle with HAL_I2C_IsDeviceReady; HAL_I2C_Mem_Read 8 bytes from 0x20 -> "MEM: HAL I2C!"; then the
 *         plain master API: HAL_I2C_Master_Transmit (word address 0x24) + HAL_I2C_Master_Receive 4 bytes ->
 *         "RX: I2C!"; finally HAL_I2C_IsDeviceReady(0x77) on an empty address -> "0x77: none" (NACK, AF).
 * Output: "I2C HAL\r\nMEM: HAL I2C!\r\nRX: I2C!\r\n0x77: none\r\n" (or "... error" lines).
 */
#include "stm32f4xx_hal.h"

UART_HandleTypeDef huart1;
I2C_HandleTypeDef hi2c1;
volatile uint32_t ready_polls;

static void SystemClock_Config(void);
static void Error_Handler(void);

static void print(const char *s)
{
    uint16_t n = 0;
    while (s[n])
        n++;
    HAL_UART_Transmit(&huart1, (uint8_t *)s, n, 100);
}

static void clear(uint8_t *b, unsigned n)
{
    while (n--)
        b[n] = 0;
}

int main(void)
{
    static const uint8_t msg[] = "HAL I2C!";
    uint8_t buf[12];

    HAL_Init();
    SystemClock_Config();

    huart1.Instance = USART1;
    huart1.Init.BaudRate = 115200;
    huart1.Init.WordLength = UART_WORDLENGTH_8B;
    huart1.Init.StopBits = UART_STOPBITS_1;
    huart1.Init.Parity = UART_PARITY_NONE;
    huart1.Init.Mode = UART_MODE_TX_RX;
    huart1.Init.HwFlowCtl = UART_HWCONTROL_NONE;
    huart1.Init.OverSampling = UART_OVERSAMPLING_16;
    if (HAL_UART_Init(&huart1) != HAL_OK)
        Error_Handler();

    hi2c1.Instance = I2C1;
    hi2c1.Init.ClockSpeed = 100000;
    hi2c1.Init.DutyCycle = I2C_DUTYCYCLE_2;
    hi2c1.Init.OwnAddress1 = 0;
    hi2c1.Init.AddressingMode = I2C_ADDRESSINGMODE_7BIT;
    hi2c1.Init.DualAddressMode = I2C_DUALADDRESS_DISABLE;
    hi2c1.Init.OwnAddress2 = 0;
    hi2c1.Init.GeneralCallMode = I2C_GENERALCALL_DISABLE;
    hi2c1.Init.NoStretchMode = I2C_NOSTRETCH_DISABLE;
    if (HAL_I2C_Init(&hi2c1) != HAL_OK)
        Error_Handler();

    print("I2C HAL\r\n");
    if (HAL_I2C_IsDeviceReady(&hi2c1, 0x50 << 1, 3, 10) != HAL_OK)
        print("0x50: none\r\n");
    if (HAL_I2C_Mem_Write(&hi2c1, 0x50 << 1, 0x20, I2C_MEMADD_SIZE_8BIT, (uint8_t *)msg, sizeof msg - 1, 50) != HAL_OK)
        print("write error\r\n");
    while (HAL_I2C_IsDeviceReady(&hi2c1, 0x50 << 1, 1, 10) != HAL_OK)
        ready_polls++;                                   /* the EEPROM NACKs during its 5 ms write cycle */
    clear(buf, sizeof buf);
    if (HAL_I2C_Mem_Read(&hi2c1, 0x50 << 1, 0x20, I2C_MEMADD_SIZE_8BIT, buf, 8, 50) == HAL_OK) {
        print("MEM: ");
        print((char *)buf);
        print("\r\n");
    } else {
        print("read error\r\n");
    }
    uint8_t waddr = 0x24;
    clear(buf, sizeof buf);
    if (HAL_I2C_Master_Transmit(&hi2c1, 0x50 << 1, &waddr, 1, 50) == HAL_OK &&
        HAL_I2C_Master_Receive(&hi2c1, 0x50 << 1, buf, 4, 50) == HAL_OK) {
        print("RX: ");
        print((char *)buf);
        print("\r\n");
    } else {
        print("master error\r\n");
    }
    print(HAL_I2C_IsDeviceReady(&hi2c1, 0x77 << 1, 2, 10) == HAL_OK ? "0x77: present\r\n" : "0x77: none\r\n");
    for (;;) {
        __WFI();
    }
}

void HAL_I2C_MspInit(I2C_HandleTypeDef *hi2c)
{
    GPIO_InitTypeDef g = {0};
    if (hi2c->Instance != I2C1)
        return;
    __HAL_RCC_GPIOB_CLK_ENABLE();
    g.Pin = GPIO_PIN_6 | GPIO_PIN_7;
    g.Mode = GPIO_MODE_AF_OD;
    g.Pull = GPIO_PULLUP;
    g.Speed = GPIO_SPEED_FREQ_VERY_HIGH;
    g.Alternate = GPIO_AF4_I2C1;
    HAL_GPIO_Init(GPIOB, &g);
    __HAL_RCC_I2C1_CLK_ENABLE();
}

void HAL_UART_MspInit(UART_HandleTypeDef *huart)
{
    GPIO_InitTypeDef g = {0};
    if (huart->Instance != USART1)
        return;
    __HAL_RCC_USART1_CLK_ENABLE();
    __HAL_RCC_GPIOA_CLK_ENABLE();
    g.Pin = GPIO_PIN_9 | GPIO_PIN_10;
    g.Mode = GPIO_MODE_AF_PP;
    g.Pull = GPIO_PULLUP;
    g.Speed = GPIO_SPEED_FREQ_VERY_HIGH;
    g.Alternate = GPIO_AF7_USART1;
    HAL_GPIO_Init(GPIOA, &g);
}

/* As generated by STM32CubeMX for an 8 MHz crystal and 168 MHz SYSCLK. */
static void SystemClock_Config(void)
{
    RCC_OscInitTypeDef osc = {0};
    RCC_ClkInitTypeDef clk = {0};

    __HAL_RCC_PWR_CLK_ENABLE();
    __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE1);

    osc.OscillatorType = RCC_OSCILLATORTYPE_HSE;
    osc.HSEState = RCC_HSE_ON;
    osc.PLL.PLLState = RCC_PLL_ON;
    osc.PLL.PLLSource = RCC_PLLSOURCE_HSE;
    osc.PLL.PLLM = 8;
    osc.PLL.PLLN = 336;
    osc.PLL.PLLP = RCC_PLLP_DIV2;
    osc.PLL.PLLQ = 7;
    if (HAL_RCC_OscConfig(&osc) != HAL_OK)
        Error_Handler();

    clk.ClockType = RCC_CLOCKTYPE_HCLK | RCC_CLOCKTYPE_SYSCLK | RCC_CLOCKTYPE_PCLK1 | RCC_CLOCKTYPE_PCLK2;
    clk.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
    clk.AHBCLKDivider = RCC_SYSCLK_DIV1;
    clk.APB1CLKDivider = RCC_HCLK_DIV4;
    clk.APB2CLKDivider = RCC_HCLK_DIV2;
    if (HAL_RCC_ClockConfig(&clk, FLASH_LATENCY_5) != HAL_OK)
        Error_Handler();
}

static void Error_Handler(void)
{
    __disable_irq();
    for (;;) { }
}

void SysTick_Handler(void)
{
    HAL_IncTick();
}
